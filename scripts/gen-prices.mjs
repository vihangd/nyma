#!/usr/bin/env bun
// Regenerates src/agent/pricing_data.cljs from models.dev.
//
// Prices were typed in by hand from whatever page was open at the time, and a
// commit could not tell a quoted figure from a derived one (ab36078 said
// "quoted"; its cache-write column was 1.25x input, worked out). models.dev is
// MIT-licensed, per-1M USD like our table, and carries context windows and
// input modalities too — the PDF gate reads the latter.
//
// Run:   bun run gen:prices            fetch and rewrite the file
//        bun run gen:prices --check    exit 1 when the file is stale (network)
//        bun scripts/gen-prices.mjs --from api.json   offline, from a saved copy
//
// Hand corrections belong in agent.pricing/overrides, never in the output.

import { readFileSync, writeFileSync, existsSync } from "node:fs";

const URL = "https://models.dev/api.json";
const OUT = "src/agent/pricing_data.cljs";

// models.dev provider -> key prefix in nyma. First-party vendors are keyed by
// bare id (what `lookup-cost` falls back to); hosts that carry other vendors'
// models are keyed `provider/id`, so their rate never answers for the vendor's.
const PROVIDERS = {
  anthropic: "",
  openai: "",
  google: "",
  deepseek: "deepseek/",
  moonshotai: "kimi/",
  minimax: "minimax/",
  groq: "groq/",
  openrouter: "openrouter/",
};

const num = (v) => (typeof v === "number" && Number.isFinite(v) && v >= 0 ? v : null);

/** models.dev JSON -> sorted {prices, context, output, pdf} keyed as nyma looks them up. */
export function extract(data) {
  const prices = {}, context = {}, output = {}, pdf = [];
  for (const [prov, prefix] of Object.entries(PROVIDERS)) {
    for (const [id, m] of Object.entries(data[prov]?.models ?? {})) {
      if (!(m.modalities?.output ?? ["text"]).includes("text")) continue;
      const key = prefix + id;
      const c = m.cost;
      if (c && num(c.input) !== null && num(c.output) !== null) {
        const row = [c.input, c.output, num(c.cache_read), num(c.cache_write)];
        while (row.length > 2 && row[row.length - 1] === null) row.pop();
        prices[key] = row;
      }
      if (num(m.limit?.context)) context[key] = m.limit.context;
      if (num(m.limit?.output)) output[key] = m.limit.output;
      if (m.modalities?.input?.includes("pdf")) pdf.push(key);
    }
  }
  const sorted = (o) => Object.fromEntries(Object.keys(o).sort().map((k) => [k, o[k]]));
  return { prices: sorted(prices), context: sorted(context), output: sorted(output), pdf: pdf.sort() };
}

const v = (x) => (x === null ? "nil" : String(x));

export function render(data, date = new Date().toISOString().slice(0, 10)) {
  const { prices, context, output, pdf } = extract(data);
  const map = (o, f) =>
    "{" + Object.entries(o).map(([k, x]) => `${JSON.stringify(k)} ${f(x)}`).join("\n   ") + "}";
  return `(ns agent.pricing-data
  "Model prices, context windows, output limits and PDF input, from models.dev.

   Generated by scripts/gen-prices.mjs from ${URL} — do not edit by hand.
   Refresh with 'bun run gen:prices'; corrections go in agent.pricing/overrides.")

(def fetched ${JSON.stringify(date)})

;; USD per 1M tokens: [input output] or [input output cache-read cache-write].
(def prices
  ${map(prices, (r) => `[${r.map(v).join(" ")}]`)})

(def context
  ${map(context, String)})

(def output-limit
  ${map(output, String)})

(def pdf-input
  #{${pdf.map((k) => JSON.stringify(k)).join("\n    ")}})
`;
}

const stripDate = (s) => s.replace(/^\(def fetched .*$/m, "");

if (import.meta.main) {
  const args = process.argv.slice(2);
  const from = args.includes("--from") ? args[args.indexOf("--from") + 1] : null;
  const data = from
    ? JSON.parse(readFileSync(from, "utf8"))
    : await fetch(URL, { signal: AbortSignal.timeout(30000) }).then((r) => {
        if (!r.ok) throw new Error(`${URL}: HTTP ${r.status}`);
        return r.json();
      });
  if (!data?.anthropic?.models) throw new Error(`${URL}: unexpected shape (no anthropic models)`);
  const out = render(data);
  if (args.includes("--check")) {
    const cur = existsSync(OUT) ? readFileSync(OUT, "utf8") : "";
    if (stripDate(cur) !== stripDate(out)) {
      console.error(`${OUT} is stale — run: bun run gen:prices`);
      process.exit(1);
    }
    console.log(`${OUT} is current`);
  } else {
    writeFileSync(OUT, out);
    const n = Object.keys(extract(data).prices).length;
    console.log(`wrote ${OUT}: ${n} priced models`);
  }
}
