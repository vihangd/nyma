#!/usr/bin/env bun
// Regenerates bench/RESULTS.md — one row per benchmark run.
//
// The numbers lived only inside 119 JSON files and in commit messages, so
// comparing two arms meant opening both and adding a column up by hand, and a
// figure quoted in prose had no provenance attached to it.
//
// Every headline figure is RECOMPUTED from `results[]` rather than read from the
// stored `cost` block, because older files predate the denominator fix: a
// timed-out task reports no usage at all, and dividing the tokens we did see by
// every attempted task understates the per-task figure by exactly the expensive
// tail. `baseline-js25-local` stores 174,845 and the honest figure is 190,049 —
// a 9% gap on the run every later arm is compared against. Reading the stored
// field would bake that in permanently.
//
// Run: bun run gen:bench-ledger

import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import * as path from "node:path";

const DIR = "bench/results";

function summarize(file) {
  const d = JSON.parse(readFileSync(path.join(DIR, file), "utf8"));
  const rs = d.results ?? [];
  if (!rs.length) return null;
  // Only tasks that reported usage; `n` says how many did not.
  const rep = rs.filter((r) => r.tokens != null);
  const sum = (xs, k) => xs.reduce((a, r) => a + (Number(r[k]) || 0), 0);
  const inputTok = sum(rep, "inputTokens");
  const tools = {};
  for (const r of rs) for (const [t, n] of Object.entries(r.toolsUsed ?? {})) tools[t] = (tools[t] ?? 0) + n;
  return {
    file,
    label: d.label ?? "-",
    sha: d.gitSha ?? "-",
    model: String(d.model ?? "-"),
    tasks: rs.length,
    langs: [...new Set(rs.map((r) => String(r.id).split("/")[0]))].sort().join("+"),
    pass: Math.round((100 * rs.filter((r) => r.status === "pass").length) / rs.length),
    timeout: rs.filter((r) => r.status === "timeout").length,
    tokPerTask: rep.length ? Math.round(sum(rep, "tokens") / rep.length) : null,
    // A zero here means the route reported NO cache tokens, which is not the
    // same claim as a 0% hit rate — vLLM answers `prompt_tokens_details: null`
    // on every request. Printing 0 invited exactly that misreading once already.
    cachePct: inputTok && sum(rep, "cacheRead") > 0
      ? Math.round((1000 * sum(rep, "cacheRead")) / inputTok) / 10
      : null,
    // Server-sampled prefix cache, for a route that reports no per-request
    // cache tokens at all (vLLM). Distinct from the column above on purpose.
    serverCachePct: d.serverPrefixCache?.sharePct ?? null,
    turns: sum(rep, "turns") || null,
    toolCalls: sum(rs, "toolCalls") || null,
    edits: (tools.edit ?? 0) + (tools.multi_edit ?? 0),
    writes: tools.write ?? 0,
    wallMin: Math.round(sum(rs, "durationMs") / 60000),
    reported: `${rep.length}/${rs.length}`,
    smallModel: Boolean(d.agentSettings?.["small-model"]?.enabled),
    timeoutMs: d.timeoutMs ?? null,
    concurrency: d.concurrency ?? null,
  };
}

const rows = readdirSync(DIR)
  .filter((f) => f.endsWith(".json") && f !== "latest.json")
  .map((f) => { try { return summarize(f); } catch { return null; } })
  .filter(Boolean)
  .sort((a, b) => (a.file < b.file ? -1 : 1));

const n = (v) => (v == null ? "-" : typeof v === "number" ? v.toLocaleString("en-US") : v);
const head = `# Benchmark results ledger

Generated by \`bun run gen:bench-ledger\` — do not hand-edit.

Every figure here is **recomputed from \`results[]\`**, not read from the stored
\`cost\` block. Older files predate the denominator fix, where a timed-out task
reports no usage and dividing by all attempted tasks understates the per-task
cost by exactly the expensive tail. \`baseline-js25-local\` stores 174,845 where
the honest figure is 190,049.

\`tok/task\` averages over the tasks that **reported** usage; \`rep\` is how many
of how many did. \`cache%\` is the per-request share of input served from cache,
and is blank for a server that reports no cache tokens — for those, \`srv%\` is
the server-sampled prefix-cache rate over the run. \`sm\` marks an arm with the
small-model extension enabled.

A run is only comparable to another at the same model, task set and sha lineage.
The columns are here so that is checkable rather than assumed.

| run | label | sha | model | tasks | pass | t/o | tok/task | cache% | srv% | turns | calls | edit | write | wall | rep | sm |
|---|---|---|---|---|---|---|---|---|---|---|---|---|---|---|---|---|`;

const body = rows.map((r) =>
  `| ${r.file.replace(/\.json$/, "")} | ${r.label} | \`${r.sha}\` | ${r.model} | ${r.tasks} ${r.langs} | ${r.pass}% | ${r.timeout} | ${n(r.tokPerTask)} | ${r.cachePct ?? "-"} | ${r.serverCachePct ?? "-"} | ${n(r.turns)} | ${n(r.toolCalls)} | ${r.edits} | ${r.writes} | ${r.wallMin}m | ${r.reported} | ${r.smallModel ? "yes" : ""} |`
).join("\n");

const out = `${head}\n${body}\n`;
writeFileSync("bench/RESULTS.md", out);
console.log(`bench/RESULTS.md — ${rows.length} runs`);
