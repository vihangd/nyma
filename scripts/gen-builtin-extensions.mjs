#!/usr/bin/env bun
// Regenerates src/agent/builtin_extensions.cljs.
//
// Builtin extensions used to be found only by scanning dist/agent/extensions at
// runtime. That works from a source tree and cannot work from a single-file
// binary: `builtin-extensions-dir` resolves inside the bundle, where no such
// directory exists, so `bun run bundle` produced a nyma with 2 of 40 extensions
// and 3 of 20 providers — silently, because an empty scan is not an error.
//
// Static requires put every builtin in the bundle graph instead. The manifests
// are inlined for the same reason: extension.json is a file read, and there are
// no files inside the binary either.
//
// Run: bun run gen:builtins   (the drift test fails if the file is stale)

import { readdirSync, readFileSync, existsSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const SRC = "src/agent/extensions";
const OUT = "src/agent/builtin_extensions.cljs";

const kebab = (s) => s.replaceAll("_", "-");

/** Directories under src/agent/extensions that are loadable extensions. */
export function builtinDirs(root = SRC) {
  return readdirSync(root, { withFileTypes: true })
    .filter((e) => e.isDirectory() && existsSync(join(root, e.name, "index.cljs")))
    .map((e) => e.name)
    .sort();
}

/** JSON value -> squint `#js` literal. Manifests are read with `.-field`.
 *  Keys are emitted as STRINGS, not keywords: a dependency name like
 *  "@anthropic-ai/claude-agent-sdk" is not a valid keyword and fails the
 *  compile. The resulting JS object is identical either way. */
function toCljs(v) {
  if (v === null || v === undefined) return "nil";
  if (Array.isArray(v)) return `#js [${v.map(toCljs).join(" ")}]`;
  if (typeof v === "object") {
    const pairs = Object.entries(v).map(([k, val]) => `${JSON.stringify(k)} ${toCljs(val)}`);
    return `#js {${pairs.join(" ")}}`;
  }
  if (typeof v === "string") return JSON.stringify(v);
  return String(v);
}

export function render(root = SRC) {
  const dirs = builtinDirs(root);
  const entries = dirs.map((dir) => {
    const manifestPath = join(root, dir, "extension.json");
    const manifest = existsSync(manifestPath)
      ? JSON.parse(readFileSync(manifestPath, "utf8"))
      : null;
    return {
      dir,
      alias: `ext-${kebab(dir)}`,
      ns: `agent.extensions.${kebab(dir)}.index`,
      namespace: manifest?.namespace ?? kebab(dir),
      manifest,
    };
  });

  const requires = entries
    .map((e, i) => `${i === 0 ? "" : "            "}[${e.ns} :as ${e.alias}]`)
    .join("\n");

  const rows = entries
    .map(
      (e) =>
        `   {:namespace ${JSON.stringify(e.namespace)}\n` +
        `    :module    ${e.alias}\n` +
        `    :manifest  ${toCljs(e.manifest)}}`,
    )
    .join("\n");

  return `(ns agent.builtin-extensions
  "Every builtin extension, imported statically.

   Generated by scripts/gen-builtin-extensions.mjs — do not edit by hand.
   Run 'bun run gen:builtins' after adding or removing an extension;
   test/builtin_extensions.test.cljs fails when this file is stale.

   Why static: the loader used to find these by scanning the directory they
   compile into, which cannot work inside a single-file binary — the scan path
   resolves into the bundle, finds nothing, and an empty scan is not an error. A
   bundled nyma therefore shipped with 2 of 40 extensions and 3 of 20 providers.
   Static requires put them in the bundle graph, and the manifests are inlined
   because extension.json is a file read that has nowhere to read from either.

   User extensions are unaffected: they are still discovered by scanning
   ~/.nyma/extensions and .nyma/extensions, which are real directories on the
   machine running nyma."
  (:require ${requires}))

(def registry
  "[{:namespace :module :manifest}] — fed to extension-loader/discover-and-load
   alongside the user-directory scan, and run through the same topological sort,
   capability parsing and activation as anything it finds on disk."
  [
${rows}])
`;
}

/** The README's "Built-in Extensions" table, from each manifest's
 *  `description`. The hand-kept table listed an extension that did not
 *  exist and missed two that did. */
export function renderReadmeTable(root = SRC) {
  const rows = builtinDirs(root).map((dir) => {
    const p = join(root, dir, "extension.json");
    const m = existsSync(p) ? JSON.parse(readFileSync(p, "utf8")) : {};
    const desc = m.description ?? "";
    return `| \`${dir}\` | \`${m.namespace ?? kebab(dir)}\` | ${desc} |`;
  });
  return ["| Extension | Namespace | Purpose |", "|-----------|-----------|---------|", ...rows].join("\n");
}

export const README_START = "<!-- generated: builtin-extensions (bun run gen:builtins) -->";
export const README_END = "<!-- /generated: builtin-extensions -->";

/** README with the generated block replaced. Returns null when the markers are absent. */
export function spliceReadme(readme, table) {
  const i = readme.indexOf(README_START), j = readme.indexOf(README_END);
  if (i < 0 || j < 0) return null;
  return readme.slice(0, i + README_START.length) + "\n" + table + "\n" + readme.slice(j);
}

if (import.meta.main) {
  const out = render();
  writeFileSync(OUT, out);
  console.log(`${OUT} — ${builtinDirs().length} builtin extensions`);
  const readme = readFileSync("README.md", "utf8");
  const spliced = spliceReadme(readme, renderReadmeTable());
  if (spliced === null) console.log("README.md — no generated-table markers, left alone");
  else if (spliced !== readme) { writeFileSync("README.md", spliced); console.log("README.md — builtin table regenerated"); }
}
